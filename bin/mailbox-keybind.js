#!/usr/bin/env node
const fs = require('fs');
const crypto = require('crypto');
const os = require('os');
const path = require('path');
const { readText, readJson, LIMITS } = require(path.join(__dirname, 'mailbox-bounded-read.js'));
const { spawnSync } = require('child_process');

const settingsPath = path.join(os.homedir(), '.config', 'omarchy', 'mailbox.json');
const hyprDir = path.join(os.homedir(), '.config', 'hypr');
const bindingPath = path.join(hyprDir, 'mailbox.lua');
const mainPath = path.join(hyprDir, 'hyprland.lua');
const requireLine = 'require("hypr.mailbox")';
const legacyRequireLine = 'require("mailbox")';

// Replace a user-owned file atomically: random temp name, O_EXCL|O_NOFOLLOW, no symlinked target.
function atomicWrite(file, text, mode = 0o600) {
  let stat = null;
  try { stat = fs.lstatSync(file); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (stat && (!stat.isFile() || stat.uid !== process.getuid())) throw new Error(`Unsafe file: ${file}`);
  const temp = `${file}.${process.pid}.${crypto.randomBytes(12).toString('hex')}.tmp`;
  let fd;
  try {
    fd = fs.openSync(temp, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_NOFOLLOW, mode);
    fs.writeFileSync(fd, text);
    fs.closeSync(fd);
    fd = undefined;
    fs.renameSync(temp, file);
  } finally {
    if (fd !== undefined) fs.closeSync(fd);
    fs.rmSync(temp, { force: true });
  }
}
const blockStart = '-- BEGIN omarchy-mailbox keybinding';
const blockEnd = '-- END omarchy-mailbox keybinding';
function updateMain(includeBinding) {
  if (!fs.existsSync(mainPath)) {
    if (includeBinding) throw new Error(`Missing Hyprland configuration: ${mainPath}`);
    return;
  }
  const original = readText(mainPath, LIMITS.config);
  const mode = fs.lstatSync(mainPath).mode & 0o777;
  const newline = original.includes('\r\n') ? '\r\n' : '\n';
  let next = original;
  const start = next.indexOf(blockStart), end = next.indexOf(blockEnd);
  if (start !== -1 || end !== -1) {
    if (start < 0 || end < start || next.indexOf(blockStart, start + 1) !== -1 || next.indexOf(blockEnd, end + 1) !== -1) throw new Error('Malformed Mailbox keybinding block');
    const marker = next.startsWith(blockStart + ' (appended newline)', start) ? blockStart + ' (appended newline)' : blockStart;
    const block = next.slice(start, end + blockEnd.length);
    if ((start > 0 && next[start - 1] !== '\n') || block !== [marker, requireLine, blockEnd].join(newline)
        || (marker !== blockStart && (start < newline.length || next.slice(start - newline.length, start) !== newline))
        || (end + blockEnd.length < next.length && !next.startsWith(newline, end + blockEnd.length))) throw new Error('Modified Mailbox keybinding block');
    const lineEnd = next.startsWith(newline, end + blockEnd.length) ? newline.length : 0;
    const removeStart = marker === blockStart ? start : start - newline.length;
    next = next.slice(0, removeStart) + next.slice(end + blockEnd.length + lineEnd);
  }
  // Migrate only standalone require lines emitted by released helpers. Keep
  // every byte outside these owned lines, including blank lines and CRLF.
  next = next.replace(/^[\t ]*require\(["'](?:hypr\.)?mailbox["']\)[\t ]*(?:\r?\n|$)/gm, '');
  if (/require\s*\(?\s*["'](?:hypr\.)?mailbox["']/.test(next)) throw new Error('Edited legacy Mailbox reference; configuration left unchanged');
  if (includeBinding) {
    const separator = next && !next.endsWith('\n') ? newline : '';
    const marker = blockStart + (separator ? ' (appended newline)' : '');
    next += separator + [marker, requireLine, blockEnd, ''].join(newline);
  }
  if (next === original) return;
  const backup = `${mainPath}.mailbox-backup.${Date.now()}.${crypto.randomBytes(8).toString('hex')}`;
  const fd = fs.openSync(backup, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_NOFOLLOW, 0o600);
  try { fs.writeFileSync(fd, original); } finally { fs.closeSync(fd); }
  atomicWrite(mainPath, next, mode);
}

function reloadHyprland() {
  const reload = spawnSync('hyprctl', ['reload'], { encoding: 'utf8', timeout: 5000, maxBuffer: 64 * 1024 });
  if (reload.status !== 0) throw new Error((reload.stderr || reload.stdout || 'Hyprland reload failed').trim());
}

if (process.argv.includes('--uninstall')) {
  updateMain(false);
  fs.rmSync(bindingPath, { force: true });
  reloadHyprland();
  console.log(JSON.stringify({ removed: true }));
  process.exit(0);
}

let settings = {};
try { settings = readJson(settingsPath, LIMITS.settings); } catch (_) {}
const requested = String(process.argv[2] || settings.shortcutKey || 'Q').trim().toUpperCase();
if (!/^[A-Z]$/.test(requested)) throw new Error('Shortcut must be one letter from A to Z.');

fs.mkdirSync(hyprDir, { recursive: true, mode: 0o700 });
const lua = [
  '-- Auto-generated by Mailbox. Preferences owns this file.',
  `pcall(function() hl.unbind("SUPER + SHIFT + ${requested}") end)`,
  `o.bind("SUPER + SHIFT + ${requested}", "Mailbox", "omarchy-shell -q shell toggle io.github.avillagran.omarchy-mailbox")`,
  ''
].join('\n');
atomicWrite(bindingPath, lua);
updateMain(true);
reloadHyprland();
console.log(JSON.stringify({ shortcutKey: requested, binding: `SUPER + SHIFT + ${requested}` }));
